# =============================================================================
# extend_report_A.R - 用户第三步后处理：将阶段 A 报告
# extend_report_A.R - user step 3 post-processing: extend the stage A report
# （report_A.tsv）扩充参考格式列（多引擎 pFind
# (report_A.tsv) with the reference-format columns (multi-engine pFind
# 序列/修饰字符串、最佳组、蛋白/位点/两侧残基、
# sequence/modification strings, best group, protein / position / flanking
# 错误类型判定），与生产版判定输出保持一致。
# residues, error-type judgment), mirroring the production judgment output.
# 就地重写 <stageA>/report_A.tsv。
# Rewrites <stageA>/report_A.tsv in place.
#
# 用法：
# Usage:
#   运行方式：Rscript extend_report_A.R
#   Rscript extend_report_A.R
# 第三步参数文件路径放在 CONFIG3 中。SAP 索引自动定位于
# with the step-3 parameter file path in CONFIG3. The SAP index is located
# <merge>/SAP_spectra_index.txt（由第二步驱动程序
# automatically at <merge>/SAP_spectra_index.txt (generated by the
# 从补充搜库结果生成）；
# step-2 driver from the supplementary search results); when absent the SAP
# 该文件不存在时跳过 SAP 检查。
# check is skipped.
# =============================================================================

# 加载通用工具函数（配置解析、fasta 读取、报告扩充核心等）
# Load the shared utility functions (config parsing, fasta reader, report-extension core, etc.)
# 核心库统一入口（N-1，2026-09-25）：按 --file= 定位代码目录、绝对路径加载
# （boot.R），替代裸相对 source——此前仅当启动 cwd 恰为 code/ 时成立。
# core-library entry (N-1, 2026-09-25): locate the code dir via --file= and
# load by absolute path (boot.R), replacing the bare relative source().
sd0 <- dirname(tryCatch(normalizePath(sub("^--file=", "",
    grep("^--file=", commandArgs(FALSE), value = TRUE)[1]), winslash = "/"),
    error = function(e) ""))
if (is.na(sd0) || !dir.exists(sd0)) sd0 <- getwd()
source(file.path(sd0, "boot.R"))

# 读取第三步参数文件与基础配置，并定位阶段 A 输出目录
# Read the step-3 parameter file and the base config, and locate the stage A output directory
cfg3_path <- Sys.getenv("CONFIG3")
if (!nzchar(cfg3_path)) stop("set CONFIG3 to the step-3 parameter file path")
cfg3 <- read_param_file(cfg3_path)
bcfg_paths <- resolve_cfg_paths(cfg3, "base_config")
if (length(bcfg_paths) == 0 || is.na(bcfg_paths[1])) {
  stop("config_step3.txt 缺少 base_config\nbase_config missing in config_step3.txt")
}
base_cfg <- read_param_file(bcfg_paths[1])
# 结果文件夹（RESULT_DIR 由总程序注入；独立运行按时间戳定位/新建）
# result folder (RESULT_DIR injected by the master; standalone runs locate/create by timestamp)
sa_dir <- file.path(get_result_dir(cfg3$config_dir), "1.unlabeled_result")

# 读入阶段 A 产物：report_A.tsv（报告）、scan_details_A.tsv（谱细节）与多引擎合并结果
# Read the stage A products: report_A.tsv (report), scan_details_A.tsv (scan details) and the multi-engine merge result
for (f in c(file.path(sa_dir, "report_A.tsv"), file.path(sa_dir, "scan_details_A.tsv"))) {
  if (!file.exists(f)) stop("阶段 A 产物缺失：", f, "\nstage A output missing: ", f)
}
merge_path <- resolve_cfg_paths(cfg3, "merge_result")
if (length(merge_path) == 0 || is.na(merge_path[1]) || !file.exists(merge_path[1])) {
  stop("合并结果缺失：", if (length(merge_path) > 0 && !is.na(merge_path[1])) merge_path[1] else "(merge_result 键缺失)",
       "\nmerge result missing")
}
report <- read.delim(file.path(sa_dir, "report_A.tsv"), sep = "\t",
                     stringsAsFactors = FALSE, check.names = FALSE,
                     na.strings = character(0))
details <- read.delim(file.path(sa_dir, "scan_details_A.tsv"), sep = "\t",
                      stringsAsFactors = FALSE, check.names = FALSE,
                      na.strings = character(0))
merged <- read.delim(merge_path[1], sep = "\t",
                     stringsAsFactors = FALSE, check.names = FALSE,
                     na.strings = character(0))
# 解析 fasta 路径；SAP 清单存在则读入（UTF-8），不存在则以 NULL 表示跳过
# Resolve the fasta path; read the SAP index when present (UTF-8), otherwise NULL to skip
fasta_path <- resolve_cfg_paths(base_cfg, "fasta")[1]
# SAP 清单由第二步自动生成（UTF-8）；不存在则跳过
# SAP index auto-generated by step 2 (UTF-8); skipped when absent
sap_file <- file.path(get_result_dir(cfg3$config_dir), "merge", "SAP_spectra_index.txt")
sap <- if (file.exists(sap_file)) {
  read.delim(sap_file, sep = "\t", stringsAsFactors = FALSE,
             check.names = FALSE, na.strings = character(0))
} else NULL
if (!is.null(sap)) {
  # 全空字符列会被 read.delim 读成逻辑 NA（空字段规则），
  # 这里把它们恢复为空字符串
  # fully-empty character columns come back as logical NA (read.delim
  # blank-field rule); restore them to empty strings
  sap[] <- lapply(sap, function(x) if (is.logical(x)) rep("", length(x)) else x)
}

# 读入 fasta 并做 I→L 变换（供候选序列归一化比较使用）
# Read the fasta and apply the I->L transform (for normalized candidate-sequence comparison)
fasta <- read_fasta(fasta_path)
# 生产版 3.match_count.R 的规则
fasta <- gsub("I", "L", fasta, fixed = TRUE)   # production 3.match_count.R rule

# 打印后处理概览：报告行数、fasta 蛋白数、SAP 行数
# Print the post-processing overview: report rows, fasta protein count and SAP row count
cat("==== [用户第三步-后处理] report_A 参考格式扩充 ====\n")
cat("==== [User Step 3 - post-process] report_A reference-format extension ====\n")
cat("report rows:", nrow(report), "| fasta proteins:",
    length(fasta), "| SAP rows:", if (is.null(sap)) 0 else nrow(sap), "\n")

# 调用报告扩充核心：按参考格式（38 列）重写报告并就地写回 report_A.tsv
# Call the report-extension core: rewrite the report in the reference format (38 columns) and write report_A.tsv back in place
ext <- extend_report_A(report, details, merged, fasta, sap)
write.table(ext, file.path(sa_dir, "report_A.tsv"), sep = "\t", row.names = FALSE,
            quote = FALSE)
cat("written:", file.path(sa_dir, "report_A.tsv"),
    "(", nrow(ext), "x", ncol(ext), ")\n")
# 输出统计信息：revise_state 分布与 Error_reason 分布（用于核对判定质量）
# Print summary statistics: revise_state and Error_reason distributions (for checking the judgment quality)
cat("revise_state distribution:\n")
print(table(ext$revise_state))
cat("Error_reason distribution:\n")
print(sort(table(ext$Error_reason[ext$Error_reason != ""]), decreasing = TRUE))
# 打印完成标记
# Print the completion marker
cat("DONE\n")
